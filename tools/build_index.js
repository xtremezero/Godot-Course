/* Node harness: loads chapter slide files with a `window` shim,
   validates deck structure, prints counts, and emits SLIDES.md. */
"use strict";
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const SLIDES_DIR = path.join(ROOT, "assets", "slides");

globalThis.window = globalThis; // slide files only touch window.DECK etc.

const files = fs.readdirSync(SLIDES_DIR).filter(f => /^ch\d+\.js$/.test(f)).sort();
for (const f of files) {
  require(path.join(SLIDES_DIR, f));
}

const DECK = globalThis.DECK || [];
const TITLES = globalThis.CHAPTER_TITLES || {};
const PARTS = globalThis.CHAPTER_PARTS || {};

let problems = 0;
for (const f of files) {
  try {
    // node --check equivalent already run separately; here catch require errors
  } catch (e) {
    console.error("LOAD FAIL", f, e.message);
    process.exit(1);
  }
}

// basic structural checks
let n = 0;
const perChapter = {};
for (const s of DECK) {
  n++;
  perChapter[s.c] = (perChapter[s.c] || 0) + 1;
  if (!s.t) { console.error(`slide ${n}: missing title`); problems++; }
  if (!s.html) { console.error(`slide ${n} (${s.t}): missing html`); problems++; }
  if (typeof s.c !== "number") { console.error(`slide ${n}: bad chapter`); problems++; }
  const opens = (s.html.match(/<pre\b/g) || []).length;
  const closes = (s.html.match(/<\/pre>/g) || []).length;
  if (opens !== closes) { console.error(`slide ${n} (${s.t}): pre mismatch ${opens}/${closes}`); problems++; }
  if (s.html.includes("<code[")) { console.error(`slide ${n} (${s.t}): malformed <code[`); problems++; }
}

console.log("Total slides:", n);
for (const ch of Object.keys(perChapter).map(Number).sort((a, b) => a - b)) {
  console.log(`  CH ${String(ch).padStart(2, "0")} ${TITLES[ch] || "?"}: ${perChapter[ch]}`);
}

// generate SLIDES.md
let md = `# Mastering Godot 4 — Curriculum Slide Index\n\n`;
md += `> ${n} slides · ${files.length} chapters · generated by \`tools/build_index.js\`\n`;
md += `> Open \`index.html\` for the interactive deck (arrow keys, C = search, copy buttons on every code block).\n`;
let lastCh = null;
let i = 0;
for (const s of DECK) {
  i++;
  if (s.c !== lastCh) {
    lastCh = s.c;
    md += `\n## ${PARTS[s.c] ? PARTS[s.c] + "\n\n" : ""}Chapter ${String(s.c).padStart(2, "0")} — ${TITLES[s.c] || ""}  *(slides ${i}–${i + perChapter[s.c] - 1})*\n\n`;
  }
  md += `### Slide ${i}: ${s.t.replace(/ — Chapter.*$/, "")}\n`;
}
fs.writeFileSync(path.join(ROOT, "SLIDES.md"), md, "utf8");
console.log("Wrote SLIDES.md");
if (problems) { console.error("PROBLEMS:", problems); process.exit(1); }
console.log("Structure OK");
